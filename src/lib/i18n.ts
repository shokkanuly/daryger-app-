// ─── Server-Side Helpers ──────────────────────────────────────────────────────
export function getT(locale: Locale) {
  const dict = translations[locale] ?? translations[DEFAULT_LOCALE];
  return (key: string): string => dict[key] ?? translations[DEFAULT_LOCALE][key] ?? key;
}

export function getLocaleFromCookieValue(val: string | undefined): Locale {
  if (val === "en" || val === "kk") return val;
  return DEFAULT_LOCALE; // first-visit → Kazakh
}

